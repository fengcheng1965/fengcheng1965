# 产品数据模型
product_schema = {
    '产品ID': str,           # 唯一标识符
    '名称': str,             # 产品名称
    '有效成分': str,         # 有效成分
    '含量': str,             # 含量
    '登记号': str,           # 农药登记号
    '生产企业': str,         # 生产企业
    '防治对象': str,         # 防治对象
    '适用作物': str,         # 适用作物
    '使用方法': str,         # 使用方法
    '毒性': str,             # 毒性
    '价格': float,           # 价格
    '市场份额': float,       # 市场份额
    '地区分布': dict,        # 地区分布
    '评价': list             # 用户评价
}

# 用户数据模型
user_schema = {
    '用户名': str,           # 用户名
    '密码': str,             # 密码（加密存储）
    '角色': str,             # 角色：农户、经销商、科研人员
    '注册信息': dict,        # 注册信息
    '偏好设置': dict,        # 偏好设置
    '浏览历史': list         # 浏览历史
}

# 市场数据模型
market_schema = {
    '日期': str,             # 日期
    '产品ID': str,           # 产品ID
    '价格': float,           # 价格
    '销量': int,             # 销量
    '地区': str              # 地区
}

# 使用反馈模型
feedback_schema = {
    '用户ID': str,           # 用户ID
    '产品ID': str,           # 产品ID
    '评价': str,             # 评价内容
    '评分': int,             # 评分
    '使用效果': str,         # 使用效果
    '不良反应': str,         # 不良反应
    '日期': str              # 日期
}